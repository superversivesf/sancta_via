/// Embeds the devotional engine's fixture packs into this package.
///
/// Run from the package root:
///
/// ```sh
/// dart tool/embed_packs.dart
/// ```
///
/// The tool reads every `.json` file in the engine's fixture pack
/// directory (sorted by filename, the order `PackLoader.loadFixturesIn`
/// applies), validates the directory through the engine's own loader so
/// a pack failing validation fails the embed, and writes the raw JSON
/// documents — keyed by pack id — into `lib/src/embedded_packs.dart` as
/// a const map. Regeneration is documented in this package's README.
library;

import 'dart:convert';
import 'dart:io';

import 'package:sancta_via_devotional_engine/sancta_via_devotional_engine.dart';

/// The engine's fixture pack directory, relative to the package root.
const String fixtureDirPath =
    '../sancta_via_devotional_engine/test/fixtures/packs';

/// The generated output file, relative to the package root.
const String outputPath = 'lib/src/embedded_packs.dart';

void main() {
  final Directory fixtureDir = Directory(fixtureDirPath);
  if (!fixtureDir.existsSync()) {
    stderr.writeln('Fixture directory not found: ${fixtureDir.path}');
    exitCode = 1;
    return;
  }

  final List<File> files = <File>[
    for (final FileSystemEntity entry in fixtureDir.listSync())
      if (entry is File && entry.path.endsWith('.json')) entry,
  ]..sort((File a, File b) => a.path.compareTo(b.path));

  if (files.isEmpty) {
    stderr.writeln('No fixture packs found in ${fixtureDir.path}');
    exitCode = 1;
    return;
  }

  // Validate the whole fixture directory through the engine first: a
  // pack that fails validation fails the embed.
  final List<ContentPack> packs = PackLoader.loadFixturesIn(fixtureDir.path);
  if (packs.length != files.length) {
    stderr.writeln(
      'Fixture validation loaded ${packs.length} packs from '
      '${files.length} files',
    );
    exitCode = 1;
    return;
  }

  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_packs.dart — DO NOT EDIT.')
    ..writeln('// Source: $fixtureDirPath/*.json')
    ..writeln('// Regenerate from the package root: dart tool/embed_packs.dart')
    ..writeln()
    ..writeln('// The engine fixture packs embedded as raw JSON documents,')
    ..writeln('// keyed by pack id in sorted filename order. The in-memory')
    ..writeln('// program repository parses these through PackLoader.')
    ..writeln('const Map<String, String> embeddedPackJson = <String, String>{');

  for (int i = 0; i < files.length; i++) {
    final String json = files[i].readAsStringSync();
    final String id =
        (jsonDecode(json) as Map<String, dynamic>)['id'] as String;
    if (id != packs[i].id) {
      stderr.writeln(
        'Fixture ${files[i].path} declares id "$id" but loaded as '
        '"${packs[i].id}"',
      );
      exitCode = 1;
      return;
    }
    out.writeln('  ${_dartLiteral(id)}: ${_dartLiteral(json)},');
  }
  out.writeln('};');

  final File output = File(outputPath);
  output.parent.createSync(recursive: true);
  output.writeAsStringSync(out.toString());

  // Format the generated file so regeneration is byte-stable against
  // the committed file (dart format is idempotent).
  final ProcessResult formatted = Process.runSync(
    Platform.resolvedExecutable,
    <String>['format', outputPath],
  );
  if (formatted.exitCode != 0) {
    stderr.writeln('dart format failed on $outputPath:');
    stderr.writeln(formatted.stderr);
    exitCode = 1;
    return;
  }
  stdout.writeln('Embedded ${files.length} packs into $outputPath');
}

/// Renders [value] as a single-quoted Dart string literal, escaping
/// backslashes, quotes, dollar signs, and line breaks so any fixture
/// content round-trips verbatim.
String _dartLiteral(String value) {
  final String escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r');
  return "'$escaped'";
}
